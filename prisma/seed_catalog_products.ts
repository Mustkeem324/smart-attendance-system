async function main() {
  console.log('🌱 Starting MongoDB Product Catalog Seeding...');
  await connectToDatabase();

  for (const item of CATALOG_DATA) {
    const existing = await Product.findOne({ sku: item.sku });
    if (existing) {
      Object.assign(existing, item);
      await existing.save();
      console.log(`Updated product: ${item.name} (${item.sku})`);
    } else {
      await Product.create(item);
      console.log(`Created product: ${item.name} (${item.sku})`);
    }
  }

  const total = await Product.countDocuments();
  console.log(`🎉 Seeded successfully! Total products in MongoDB catalog: ${total}`);
  process.exit(0);
}

main().catch((err) => {
  console.error('❌ Error seeding catalog products:', err);
  process.exit(1);
});
